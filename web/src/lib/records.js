/** Print or save as PDF, without leaving the app. */
export function printInvoice(inv) {
  const f = document.createElement('iframe');
  f.style.cssText = 'position:fixed;right:0;bottom:0;width:0;height:0;border:0';
  document.body.appendChild(f);
  f.contentDocument.open(); f.contentDocument.write(invoiceHtml(inv)); f.contentDocument.close();
  setTimeout(() => { try { f.contentWindow.focus(); f.contentWindow.print(); } catch { /* ignore */ } setTimeout(() => f.remove(), 60000); }, 250);
}

/** Build the evidence workbook for a period. Returns {blob, fileName, sha256, invoices, total, verifiedShare}. */
export async function buildWorkbook(s, { from, to, score }) {
  const inRange = t => t.at >= from && t.at < to;
  const ev = evidenceMap(s.ledger);
  const sales = s.txns.filter(t => t.type === 'sale' && inRange(t)).sort((a, b) => a.at - b.at);
  const invoices = sales.map(t => invoiceFor(s, t));
  const live = invoices.filter(i => !i.cancelled);
  const total = live.reduce((a, i) => a + i.total, 0);
  const verified = live.filter(i => i.verified).reduce((a, i) => a + i.total, 0);
  const chain = verifyChain(s.ledger);
  const head = s.ledger[s.ledger.length - 1];
  const p = s.profile;

  const summary = [
    ['Vendora evidence file for Wema Bank'], [],
    ['Business', p.businessName], ['Owner', p.name], ['Phone', p.phone], ['Wema account', `${p.accountNumber || ''} ${p.accountName || ''}`.trim()],
    ['Market / area', p.city], ['Shop GPS', p.location ? `${p.location.lat}, ${p.location.lng} (±${p.location.accuracy} m)` : 'Not set'],
    ['CAC', s.cac?.number || (s.cac?.status && s.cac.status !== 'none' ? `In progress (${s.cac.status})` : 'Not registered')],
    ['Period', `${new Date(from).toISOString().slice(0, 10)} to ${new Date(to - 1).toISOString().slice(0, 10)}`],
    [], ['Invoices', live.length], ['Cancelled invoices (kept on record)', invoices.length - live.length],
    ['Sales total (NGN)', total], ['Confirmed by Wema, receipt or verified seller (NGN)', verified], ['Confirmed share', total ? +(verified / total).toFixed(3) : 0],
    ['Business Score', score?.score ?? ''], ['Score band', score?.band ?? ''], [],
    ['Sealed record entries', s.ledger.length], ['Seal intact', chain.ok ? 'YES' : `NO: ${chain.reason}`],
    ['Latest seal', head ? `#${head.seq} ${head.hash}` : ''], ['Device key fingerprint', s.ledgerKey?.fingerprint || ''],
    ['Generated', new Date().toISOString()],
  ];
  const invRows = invoices.map(i => ({ Invoice: i.no, Date: new Date(i.at).toISOString().slice(0, 16).replace('T', ' '), Customer: i.customer,
    Items: i.items.map(x => `${x.qty} ${x.name}`).join('; '), Total: i.total, Paid: i.paid, Balance: i.balance, Payment: i.method, Proof: i.proof,
    Verified: i.verified ? 'YES' : 'no', 'Recorded by': i.staff, Cancelled: i.cancelled ? `YES: ${i.cancelledReason}` : '', Seal: i.seal }));
  const lineRows = invoices.flatMap(i => i.items.map(x => ({ Invoice: i.no, Item: x.name, Qty: x.qty, Unit: x.unit, Price: x.price, Amount: x.qty * x.price, 'Cost price': x.cost ?? '' })));
  const moneyRows = s.credits.filter(inRange).map(c => ({ Date: new Date(c.at).toISOString().slice(0, 16).replace('T', ' '), From: c.senderName, Bank: c.senderBank || '', Amount: c.amount, 'Bank reference': c.reference || '', 'Matched to': s.txns.find(t => t.id === c.linkedTxnId)?.invoiceNo || (c.handled ? 'Other income' : 'Not yet matched') }));
  const stockRows = s.txns.filter(t => t.type === 'restock' && inRange(t)).map(t => ({ Date: new Date(t.at).toISOString().slice(0, 10), Items: t.items.map(x => `${x.qty} ${x.name}`).join('; '), Cost: t.amount, Proof: EVIDENCE[ev.get(t.id)]?.label || 'Typed in', Note: t.note || '', Cancelled: t.reversed ? 'YES' : '' }));
  const debtRows = s.customers.map(c => ({ Customer: c.name, Phone: c.phone || '', 'Owes now': c.balance || 0 }));
  const loanRows = s.loans.map(l => ({ Loan: l.id, Date: new Date(l.createdAt).toISOString().slice(0, 10), Amount: l.principal, 'Paid to seller': l.supplierName, 'Total to repay': l.totalRepayable, Repaid: l.repaid, Status: l.status }));
  const sealRows = s.ledger.map(e => ({ Seq: e.seq, Time: new Date(e.at).toISOString(), Kind: e.kind, Ref: e.ref, Proof: e.evidence, Flag: e.flag || '', Hash: e.hash, Previous: e.prev, Signed: e.sig ? 'YES' : 'no' }));

  const wb = utils.book_new();
  const add = (name, rows, aoa = false) => {
    const ws = aoa ? utils.aoa_to_sheet(rows) : utils.json_to_sheet(rows.length ? rows : [{ Note: 'Nothing in this period' }]);
    const cols = aoa ? [{ wch: 42 }, { wch: 70 }] : Object.keys(rows[0] || { Note: '' }).map(k => ({ wch: Math.min(48, Math.max(10, k.length + 2, ...rows.slice(0, 50).map(r => String(r[k] ?? '').length + 1))) }));
    ws['!cols'] = cols;
    utils.book_append_sheet(wb, ws, name);
  };
  add('Summary', summary, true); add('Invoices', invRows); add('Invoice items', lineRows); add('Money in (Wema)', moneyRows);
  add('Stock deliveries', stockRows); add('Debts', debtRows); add('Loans', loanRows); add('Sealed record', sealRows);
  const bytes = write(wb, { type: 'array', bookType: 'xlsx', compression: true });
  const blob = new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
  let hash;
  try { hash = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(b => b.toString(16).padStart(2, '0')).join(''); }
  catch { let bin = ''; new Uint8Array(bytes).forEach(b => { bin += String.fromCharCode(b); }); hash = sha256(bin); }
  const slug = (p.businessName || 'vendora').replace(/\W+/g, '-').replace(/^-|-$/g, '');
  const fileName = `${slug}_records_${new Date(from).toISOString().slice(0, 7)}.xlsx`;
  return { blob, fileName, sha256: hash, invoices: live.length, total, verifiedShare: total ? verified / total : 0 };
}

/** Save a file. Inside the hosted Claude page this asks the viewer to confirm; elsewhere it downloads directly. */
export async function downloadBlob(blob, name) {
  try {
    if (typeof window !== 'undefined' && window.claude?.use) {
      const dl = await window.claude.use('downloads');
      if (dl) { await dl.save({ filename: name, data: blob }); return; }
    }
  } catch (e) { if (e && e.code === 'declined') return; }
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob); a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}
