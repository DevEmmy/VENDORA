// Invoices and the evidence workbook sent to Wema.
// The workbook carries every invoice, the proof behind each one, verified money in, verified deliveries,
// debts, loans and the full sealed record, so Wema can check the Business Score against raw evidence.
import { utils, write } from 'xlsx';
import { EVIDENCE, evidenceMap, verifyChain } from './ledger.js';
import { naira, qtyUnit } from './format.js';
import { sha256 } from './sha256.js';

const METHOD = { verified: 'Transfer, confirmed by Wema', pending: 'Transfer, waiting', unverified: 'Transfer, NOT confirmed', credit: 'On credit', cash: 'Cash' };
const d8 = t => new Date(t).toLocaleDateString('en-NG', { day: '2-digit', month: 'short', year: 'numeric' });
const tm = t => new Date(t).toLocaleTimeString('en-NG', { hour: '2-digit', minute: '2-digit' });

export function invoiceFor(s, t) {
  const ev = evidenceMap(s.ledger).get(t.id) || 'manual';
  const entry = s.ledger.find(e => e.kind === 'record' && e.ref === t.id);
  return {
    no: t.invoiceNo || '—', id: t.id, at: t.at, items: t.items || [], total: t.amount, paid: t.paid, balance: Math.max(0, t.amount - t.paid),
    customer: t.payerName || t.customerName || 'Walk-in customer', method: t.paid < t.amount && t.paid > 0 ? 'Part payment' : METHOD[t.payStatus] || 'Cash',
    proof: EVIDENCE[ev]?.label || 'Typed in', verified: !!EVIDENCE[ev]?.verified, staff: t.staffName || s.profile.name,
    cancelled: !!t.reversed, cancelledReason: t.reversedReason || '', seal: entry ? `#${entry.seq} ${entry.hash.slice(0, 16)}` : '',
    shop: { name: s.profile.businessName, owner: s.profile.name, phone: s.profile.phone, account: s.profile.accountNumber, accountName: s.profile.accountName, area: s.profile.city, location: s.profile.location, cac: s.cac?.number || null },
  };
}

export function invoiceText(inv) {
  return [
    `*${inv.shop.name}*${inv.shop.cac ? ` (${inv.shop.cac})` : ''}`,
    `Invoice ${inv.no}, ${d8(inv.at)} ${tm(inv.at)}`,
    `Customer: ${inv.customer}`, '',
    ...inv.items.map(i => `${qtyUnit(i.qty, i.unit)} ${i.name} x ${naira(i.price)} = ${naira(i.qty * i.price)}`), '',
    `Total: ${naira(inv.total)}`, `Paid: ${naira(inv.paid)}${inv.balance ? `\nBalance: ${naira(inv.balance)}` : ''}`,
    inv.shop.account ? `\nPay to: Wema Bank ${inv.shop.account} ${inv.shop.accountName}` : '',
    `Ref: ${inv.seal}`, 'Thank you!',
  ].filter(x => x !== '').join('\n');
}

